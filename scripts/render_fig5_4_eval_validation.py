#!/usr/bin/env python3
"""Render Figures 5.4 and 5.5 for the evaluator validation in Section 5.4.

Figure 5.4: approaches written down in advance that the pooled solver recovers,
grouped by task source (pf_solver_recall_20261016).
Figure 5.5: number of reference tasks per group that do not receive Yes on each
measure under evaluator v3.0, plus the number passing all five
(pf_v30_calibration_20261015, groups as in Table 5.3).
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LinearSegmentedColormap
from matplotlib.patches import Patch

RESULTS = Path("experiments/results")
OUT = Path("thesis/figures")
BLACK, DARK_GREY, PROC, GROUP, WHITE = "#000000", "#7F7F7F", "#CFCFCF", "#F2F2F2", "#FFFFFF"
GRID = "#999999"
MEASURES = [
    "target_alignment",
    "mathematical_validity",
    "prior_knowledge_accessibility",
    "familiar_approach_limits",
    "room_for_invention",
]
MEASURE_LABELS = [
    "Alignment",
    "Validity",
    "Accessibility",
    "Limits of\nfamiliar\napproaches",
    "Room for\ninvention",
]


def style() -> None:
    plt.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
            "font.size": 9,
            "axes.edgecolor": BLACK,
            "axes.linewidth": 0.9,
            "pdf.fonttype": 42,
        }
    )


def save(fig: plt.Figure, name: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f"{name}.pdf", bbox_inches="tight", pad_inches=0.04)
    fig.savefig(OUT / f"{name}.png", dpi=300, bbox_inches="tight", pad_inches=0.04)
    plt.close(fig)
    print(f"Saved {OUT}/{name}.{{pdf,png}}")


def solver_recall() -> None:
    cohorts = json.loads((RESULTS / "pf_solver_recall_20261016/summary.json").read_text())[
        "recall_by_cohort_primary_complete"
    ]["combined"]
    pipeline = [k for k in cohorts if k.startswith("pipeline")]
    rows = [
        (
            "Published PF tasks\n(12 tasks)",
            cohorts["expert_pf"]["yes"],
            cohorts["expert_pf"]["total"],
        ),
        (
            "Routine and control\ntasks (12 tasks)",
            cohorts["routine_and_control"]["yes"],
            cohorts["routine_and_control"]["total"],
        ),
        (
            "Tasks generated by\nour pipeline (52 tasks)",
            sum(cohorts[k]["yes"] for k in pipeline),
            sum(cohorts[k]["total"] for k in pipeline),
        ),
    ]
    assert sum(r[1] for r in rows) == 219 and sum(r[2] for r in rows) == 256

    fig, ax = plt.subplots(figsize=(6.4, 2.15))
    for i, (_, found, total) in enumerate(reversed(rows)):
        ax.barh(i, found, color=DARK_GREY, edgecolor=BLACK, linewidth=0.75, height=0.56, zorder=2)
        ax.barh(
            i,
            total - found,
            left=found,
            color=GROUP,
            edgecolor=BLACK,
            linewidth=0.75,
            hatch="//",
            height=0.56,
            zorder=2,
        )
        ax.text(
            total + 3,
            i,
            f"{found} of {total} ({100 * found / total:.0f}%)",
            va="center",
            fontsize=8.5,
            color=BLACK,
        )
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels([r[0] for r in reversed(rows)])
    ax.set_xlim(0, 250)
    ax.set_xlabel("Expected approaches")
    ax.grid(axis="x", linestyle="--", linewidth=0.6, color="#D8D8D8", zorder=0)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    leg = ax.legend(
        handles=[
            Patch(facecolor=DARK_GREY, edgecolor=BLACK, linewidth=0.75, label="Found by the solver"),
            Patch(facecolor=GROUP, edgecolor=BLACK, linewidth=0.75, hatch="//", label="Missed"),
        ],
        loc="upper center",
        bbox_to_anchor=(0.5, 1.3),
        ncol=2,
        frameon=True,
        fancybox=False,
        edgecolor=BLACK,
        fontsize=8.5,
    )
    leg.get_frame().set_linewidth(0.8)
    save(fig, "fig5_4_solver_recall")


def reference_outcomes() -> None:
    run = RESULTS / "pf_v30_calibration_20261015"
    outcomes = {}
    for folder in ("full_dev_jobs", "transfer_jobs"):
        for path in (run / folder).glob("*.json"):
            job = json.loads(path.read_text())
            outcomes[job["case_id"]] = {m: job["result"]["measures"][m]["value"] for m in MEASURES}
    pack = json.loads((RESULTS / "pf_measure_campaign_20261014/calibration_pack.json").read_text())
    expected = {
        c["case_id"]: c["references"]
        for c in pack["development"] + pack["transfer"] + pack["controls"]
    }
    assert len(outcomes) == 29 and all(
        outcomes[c][m] in expected[c][m]["acceptable_values"] for c in outcomes for m in MEASURES
    )

    routine = ["expert_ship", "expert_walkcycle", "synthetic_consistency_formula"]
    groups = [
        (
            "Published PF tasks",
            [c for c in outcomes if c.startswith("expert_") and c not in routine],
        ),
        ("Routine versions", routine),
        ("One-shot tasks", [c for c in outcomes if "__" in c]),
        ("Control tasks", [c for c in outcomes if c.startswith("control_")]),
        ("StructPF tasks", [c for c in outcomes if c.startswith("grounding_")]),
    ]
    assert sum(len(ids) for _, ids in groups) == 29

    shade = LinearSegmentedColormap.from_list("fail", [WHITE, "#595959"])
    fig, ax = plt.subplots(figsize=(6.4, 3.2))
    n_rows = len(groups)
    for r, (_, ids) in enumerate(groups):
        y, n = n_rows - 1 - r, len(ids)
        for c, m in enumerate(MEASURES):
            k = sum(outcomes[i][m] in ("no", "partly", "unclear") for i in ids)
            face = shade(0.18 + 0.82 * k / n) if k else WHITE
            ax.add_patch(plt.Rectangle((c, y), 1, 1, fc=face, ec=BLACK, lw=0.7))
            if k:
                ax.text(
                    c + 0.5,
                    y + 0.5,
                    f"{k} of {n}",
                    ha="center",
                    va="center",
                    fontsize=8.5,
                    color="white" if k / n > 0.55 else BLACK,
                )
        passed = sum(all(outcomes[i][m] == "yes" for m in MEASURES) for i in ids)
        ax.add_patch(
            plt.Rectangle((5.25, y), 1.1, 1, fc=PROC if passed else GROUP, ec=BLACK, lw=0.7)
        )
        ax.text(
            5.8,
            y + 0.5,
            f"{passed} of {n}",
            ha="center",
            va="center",
            fontsize=8.5,
            fontweight="bold",
            color=BLACK,
        )

    ax.set_xlim(0, 6.4)
    ax.set_ylim(0, n_rows)
    ax.set_yticks([n_rows - 1 - r + 0.5 for r in range(n_rows)])
    ax.set_yticklabels([f"{g} ({len(ids)})" for g, ids in groups])
    ax.set_xticks([c + 0.5 for c in range(5)] + [5.8])
    ax.set_xticklabels(MEASURE_LABELS + ["All five"], fontsize=8)
    ax.xaxis.tick_top()
    ax.tick_params(length=0)
    for spine in ax.spines.values():
        spine.set_visible(False)
    top = ax.get_xaxis_transform()
    ax.plot([0.03, 4.97], [1.27, 1.27], transform=top, color="#555555", lw=0.8, clip_on=False)
    ax.text(
        2.5,
        1.30,
        "Tasks not passing this measure",
        transform=top,
        ha="center",
        va="bottom",
        fontsize=8.5,
        fontweight="bold",
    )
    ax.plot([5.28, 6.32], [1.27, 1.27], transform=top, color="#555555", lw=0.8, clip_on=False)
    ax.text(
        5.8,
        1.30,
        "Tasks that pass",
        transform=top,
        ha="center",
        va="bottom",
        fontsize=8.5,
        fontweight="bold",
    )
    save(fig, "fig5_5_reference_outcomes")


def main() -> None:
    style()
    solver_recall()
    reference_outcomes()


if __name__ == "__main__":
    main()
